      DOUBLE PRECISION FUNCTION bcd(n,k)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
* Binomial coefficient of (n k), divided by 2^n
      inum = 1
      idenom = 1
      do 10 i = k+1,n
         inum = inum * i
         idenom = idenom * (i-k)
 10   continue
      ibc = inum / idenom
      bcd = dble(ibc)/2**n
      return
      end

      DOUBLE PRECISION FUNCTION zbrentd(FUNC,X1,X2,fx1,fx2,TOL)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
      PARAMETER (ITMAX=100,EPS=3.D-8)
      EXTERNAL FUNC
      zbrentd = 0
      A=X1
      B=X2
C      FA=FUNC(A)
C      FB=FUNC(B)
      FA=Fx1
      FB=Fx2
      IF(FB*FA.GT.0.D0) THEN
         write(6,*) 'Root must be bracketed for ZBRENT.'
         return
      END IF
      FC=FB
      DO 11 ITER=1,ITMAX
        IF(FB*FC.GT.0.D0) THEN
          C=A
          FC=FA
          D=B-A
          E=D
        ENDIF
        IF(ABS(FC).LT.ABS(FB)) THEN
          A=B
          B=C
          C=A
          FA=FB
          FB=FC
          FC=FA
        ENDIF
        TOL1=2.D0*EPS*ABS(B)+0.5D0*TOL
        XM=.5D0*(C-B)
        IF(ABS(XM).LE.TOL1 .OR. FB.EQ.0.D0)THEN
          zbrentd=B
          RETURN
        ENDIF
        IF(ABS(E).GE.TOL1 .AND. ABS(FA).GT.ABS(FB)) THEN
          S=FB/FA
          IF(A.EQ.C) THEN
            P=2.D0*XM*S
            Q=1.D0-S
          ELSE
            Q=FA/FC
            R=FB/FC
            P=S*(2.D0*XM*Q*(Q-R)-(B-A)*(R-1.D0))
            Q=(Q-1.D0)*(R-1.D0)*(S-1.D0)
          ENDIF
          IF(P.GT.0.D0) Q=-Q
          P=ABS(P)
          IF(2.D0*P .LT. MIN(3.D0*XM*Q-ABS(TOL1*Q),ABS(E*Q))) THEN
            E=D
            D=P/Q
          ELSE
            D=XM
            E=D
          ENDIF
        ELSE
          D=XM
          E=D
        ENDIF
        A=B
        FA=FB
        IF(ABS(D) .GT. TOL1) THEN
          B=B+D
        ELSE
          B=B+SIGN(TOL1,XM)
        ENDIF
        FB=FUNC(B)
11    CONTINUE
      write(6,*) 'ZBRENT exceeding maximum iterations.'
      zbrentd=B
      RETURN
      END


