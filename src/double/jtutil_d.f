      SUBROUTINE dofitlpolyd(NPT,X,Y,W,SCALE,NCOEFF,COEFF,iwgt)
      IMPLICIT DOUBLE PRECISION (A-H,O-Z)
* X and Y are data arrays with NPT points to fit.
* W is a weight array, so that Sum W * (Y-Yfit)**2 is minimized
* SCALE returns A and B,
* where Z = A * (X - B) is the variable given to the polynomials.
* A polynomial of degree NCOEFF-1 is fit and the coefficients are
* returned in COEFF.
      PARAMETER (MAXFIT=8)
      double precision COV(MAXFIT*MAXFIT), VEC(MAXFIT)
      double precision COEFF(NCOEFF)
      double precision A, B, Z, LPI, DET
      double precision X(NPT), Y(NPT), SCALE(2), W(NPT)
      
      scale(1) = x(1)
      scale(2) = x(1)
      do 2 i = 2,npt
         scale(1) = min(scale(1),x(i))
         scale(2) = max(scale(2),x(i))
 2    continue

      A = 2.0D0 / (SCALE(2) - SCALE(1))
      B = 0.5D0 * (SCALE(2) + SCALE(1))
      
      DO 5 J = 1,NCOEFF
         VEC(J) = 0
 5    CONTINUE
      DO 6 I = 1,NCOEFF*NCOEFF
         COV(I) = 0
 6    CONTINUE
      DO 10 N = 1,NPT
         Z = A * (DBLE(X(N)) - B)
         
         DO 21 J = 1,NCOEFF
            COEFF(J) = LPI(J,Z)
            if(iwgt.eq.0) then
               VEC(J) = VEC(J) + COEFF(J) * Y(N)
            else
               VEC(J) = VEC(J) + COEFF(J) * Y(N) * W(N)
            end if
            DO 20 I = 1,J
               if(iwgt.eq.0) then
                  COV((J-1)*NCOEFF+I) = COV((J-1)*NCOEFF+I) + 
     $                 COEFF(I) * COEFF(J)
               else
                  COV((J-1)*NCOEFF+I) = COV((J-1)*NCOEFF+I) + 
     $                 COEFF(I) * COEFF(J) * W(N)
               end if
 20         CONTINUE
 21      CONTINUE
 10   CONTINUE
      
      DO 31 J = 2,NCOEFF
         DO 30 I = 1,J-1
            COV((I-1)*NCOEFF+J) = COV((J-1)*NCOEFF+I)
 30      CONTINUE
 31   CONTINUE
      CALL INVERT(NCOEFF,COV,DET)
      IF(DET.EQ.0) THEN
         WRITE(6,*) 'FITWLPOLY: singular covariance matrix'
         RETURN
      END IF
      
      DO 41 J = 1,NCOEFF
         COEFF(J) = 0
         DO 40 I = 1,NCOEFF
            COEFF(J) = COEFF(J) + COV((J-1)*NCOEFF+I) * VEC(I)
 40      CONTINUE
 41   CONTINUE
      SCALE(1) = dble(A)
      SCALE(2) = dble(B)
      
      RETURN
      END
      
